"""Check the stored native results are clean and match the delivered CAD files.

Does not execute KiCad/OpenSCAD; these records are generated by native_cad.py
and export_mechanical.py. Keeps ordinary CI free of large CAD installations.
"""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]

def hashes(rows):
    for row in rows:
        path=ROOT/row['path']
        assert path.resolve().is_relative_to(ROOT.resolve()),'External evidence path'
        assert path.is_file(),'Missing evidence file '+row['path']
        assert hashlib.sha256(path.read_bytes()).hexdigest()==row['sha256'],'Stale CAD evidence: '+row['path']

def main():
    record=json.loads((ROOT/'docs/records/native-cad-checks.json').read_text())
    assert record['passed'] is True and all(n==0 for n in record['checks'].values())
    assert record['version']==(ROOT/'VERSION').read_text().strip()
    hashes(record['source_hashes']);hashes(record['output_hashes'])
    drc=json.loads((ROOT/'docs/records/carrier-drc.json').read_text())
    assert all(not drc[key] for key in ('violations','unconnected_items','schematic_parity'))
    for name in ('carrier','module-system'):
        erc=json.loads((ROOT/f'docs/records/{name}-erc.json').read_text())
        assert all(not sheet['violations'] for sheet in erc['sheets'])
    mechanical=json.loads((ROOT/'docs/records/mechanical-checks.json').read_text())
    hashes(mechanical['source_hashes']);assert len(mechanical['parts'])==8
    for part in mechanical['parts']:
        assert part['closed_edge_count_check']=='PASS'
        hashes([{'path':'mechanical/exports/'+part['part']+'.stl','sha256':part['sha256']}])
    print('PASS: stored clean native ERC/DRC/parity and 8 closed meshes match delivered source/output SHA-256 hashes.')
    print('This checks stored evidence; it does not rerun native tools or perform physical tests.')
if __name__=='__main__':main()
